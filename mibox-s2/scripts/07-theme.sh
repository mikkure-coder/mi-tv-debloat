#!/usr/bin/env bash
# =============================================================================
# Обёртка подпроекта mibox-s2 — приставка Xiaomi TV Box S 2-го поколения.
# -----------------------------------------------------------------------------
# Запускает общий скрипт с тем же именем из scripts/ в корне репозитория,
# но со своими списками, бэкапами, логами и IP приставки из папки mibox-s2/.
# Телевизор и приставка поэтому друг другу не мешают.
#
# Что делает скрипт, что меняет и как откатить — в шапке общего файла
# с тем же именем: scripts/<имя этого файла> в корне репозитория.
#
# Запуск — как у телевизора, только из папки приставки, например:
#   ./mibox-s2/scripts/00-prepare.sh
#   DRY_RUN=1 ./mibox-s2/scripts/02-debloat.sh
# =============================================================================
set -euo pipefail

# Папка, где лежит эта обёртка (mibox-s2/scripts), и папка устройства (mibox-s2).
HERE="$(cd "$(dirname "$0")" && pwd)"
DEVICE_DIR="$(dirname "$HERE")"
# export — чтобы папку устройства увидел и общий скрипт, и всё, что он
# запускает сам (например, 99-restore.sh вызывает 07-theme.sh).
export DEVICE_DIR

# exec — заменить эту обёртку общим скриптом, передав ему все аргументы.
exec "$HERE/../../scripts/$(basename "$0")" "$@"
